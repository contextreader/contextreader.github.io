// Rewrites the language list in docs/index.html from lib/languages.js.
//
// The site lists every language the extension offers. It is generated, not
// typed, so the two cannot drift; test/copy.test.js fails if they do. Run this
// after changing lib/languages.js, or after redesigning the page — keep the
// two marker comments, and style `ul.langs` however the design wants.
//
//   node scripts/site-languages.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const L = createRequire(import.meta.url)(join(ROOT, 'lib/languages.js'));
const PAGE = join(ROOT, 'docs/index.html');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const START = '<!-- languages:start';
const END = '<!-- languages:end -->';

// Alphabetical by English name, tuned or not. Tuned-first put English and
// Sinhala at the head of the page, which reads as a Sinhala product; the
// "tuned" label on each entry already says which are tuned.
const all = L.listLangs().slice().sort((x, y) => x.name.localeCompare(y.name, 'en'));
const item = (l) =>
    `<li${l.tuned ? ' class="tuned"' : ''}>`
    + `<span class="nat" lang="${esc(l.code)}"${l.rtl ? ' dir="rtl"' : ''}>${esc(l.nativeName)}</span>`
    + (l.nativeName === l.name ? '' : ` <span class="en">${esc(l.name)}</span>`)
    + '</li>';

const block = `${START} — generated by scripts/site-languages.mjs from lib/languages.js; test/copy.test.js checks it stays in sync -->\n`
    + `<ul class="langs">\n${all.map(item).join('\n')}\n</ul>\n${END}`;

const html = readFileSync(PAGE, 'utf8');
const a = html.indexOf(START);
const b = html.indexOf(END);
if (a < 0 || b < 0) {
    console.error(`docs/index.html has no ${START} … ${END} markers. Put them where the list should go.`);
    process.exit(1);
}
writeFileSync(PAGE, html.slice(0, a) + block + html.slice(b + END.length));
console.log(`docs/index.html: ${all.length} languages (${all.filter((l) => l.tuned).length} tuned)`);
